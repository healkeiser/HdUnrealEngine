"""Generate the Houdini node reference (docs/reference/nodes/) from the hdUE digital assets.

Run with hython after rebuilding an asset (build_render_settings_hda.py, build_substrate_hda.py):

    hython scripts/generate_node_docs.py

Each asset's Help section (the wiki help card its builder writes, which Houdini shows on F1) becomes a page laid out
like SideFX's node help: icon, summary, description, inputs, and parameters under their tabs, with the USD attribute
or parameter name, default and menu read from the asset. It also writes the pages' navigation into zensical.toml.
"""

import html
import json
import re
import shutil
from pathlib import Path

import hou

ROOT = Path(__file__).resolve().parents[1]
OTLS = ROOT / "integrations" / "houdini" / "otls"
ICONS = ROOT / "integrations" / "houdini" / "config" / "Icons"
OUT = ROOT / "docs" / "reference" / "nodes"
CONFIG = ROOT / "zensical.toml"
HEADER = "<!-- Generated by scripts/generate_node_docs.py from the hdUE digital assets. Do not edit. -->\n\n"
NAV_START = "    # Houdini nodes: generated by scripts/generate_node_docs.py.\n"
NAV_END = "    # End of the Houdini nodes.\n"


def figure_index():
    """{USD attribute: figure} from the figure specs that name their setting: node pages show the reference's pictures."""
    index = {}
    for path in sorted((ROOT / "docs" / "figures").glob("*.json")):
        for attribute in json.loads(path.read_text(encoding="utf-8")).get(
            "settings", []
        ):
            index.setdefault(attribute, path.stem)
    return index


FIGURES = figure_index()
CONTEXTS = {
    "lop": ("LOP", "Solaris nodes (LOPs)"),
    "vop": ("VOP", "Substrate Builder nodes (VOPs)"),
}


def parse(card):
    """The help card's title, #key: value metadata, summary, description lines and @sections.

    A section is a list of ("heading", level, text) and ("entry", label, id, help lines) items, in order.
    """
    title, meta, summary, body, sections = "", {}, "", [], {}
    current = None
    lines = card.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if current is None and line.startswith("= ") and not title:
            title = line.strip("= ").strip()
        elif current is None and re.match(r"#\w+:", line):
            key, value = line[1:].split(":", 1)
            meta[key] = value.strip()
        elif current is None and line.startswith('"""'):
            summary = line.strip('"').strip()
        elif line.startswith("@"):
            current = sections.setdefault(line[1:].strip(), [])
        elif current is None:
            body.append(line)
        elif m := re.match(r"(=+) (.*?) =+$", line):
            current.append(("heading", len(m.group(1)), m.group(2)))
        elif line and not line[0].isspace() and line.endswith(":"):
            parm, text = None, []
            while i < len(lines) and (not lines[i] or lines[i][0].isspace()):
                item = lines[i].strip()
                i += 1
                if item.startswith("#id:"):
                    parm = item[4:].strip()
                elif item or text:
                    text.append(item)
            current.append(("entry", line[:-1], parm, text))
    return title, meta, summary, body, sections


def paragraphs(lines):
    """Help lines as Markdown paragraphs (blank lines separate them, as in the wiki)."""
    return "\n".join(lines).strip()


def number(value):
    return f"{value:g}" if isinstance(value, float) else str(value)


def facts_html(facts):
    """The facts strip (docs/assets/hdue.css .hdue-facts): each fact a small label over its value."""
    cells = "".join(
        f"<div><dt>{label}</dt><dd>{value}</dd></div>" for label, value in facts
    )
    return f'<dl class="hdue-facts">{cells}</dl>'


def code(text):
    return f"<code>{html.escape(text)}</code>"


def details(definition, parm):
    """The parameter's USD attribute (or name), default and menu, from the asset's parameter template, as facts."""
    template = definition.parmTemplateGroup().find(parm) if parm else None
    if template is None:
        return [("Parameter", code(parm))] if parm else []
    if parm.startswith("xn__"):
        facts = [("USD attribute", code(hou.text.decode(parm)))]
    else:
        facts = [("Parameter", code(parm))]
    kind = template.type()
    if kind == hou.parmTemplateType.Toggle:
        facts.append(("Default", "On" if template.defaultValue() else "Off"))
    elif kind == hou.parmTemplateType.Menu:
        labels, items = template.menuLabels(), template.menuItems()
        if labels:
            facts.append(
                ("Default", html.escape(labels[template.defaultValue()]))
            )
            facts.append(("Menu", html.escape(", ".join(labels))))
        elif items:
            facts.append(
                ("Default", html.escape(items[template.defaultValue()]))
            )
    elif kind in (hou.parmTemplateType.Float, hou.parmTemplateType.Int):
        values = template.defaultValue()
        if values:
            facts.append(("Default", ", ".join(number(v) for v in values)))
    elif kind == hou.parmTemplateType.String:
        values = [v for v in template.defaultValue() if v]
        if values:
            facts.append(("Default", code(", ".join(values))))
        if template.menuLabels():
            facts.append(
                ("Menu", html.escape(", ".join(template.menuLabels())))
            )
    return facts


def section(definition, items):
    """A section's entries as SideFX's help lays them out: a grid of rows, the name beside its help, facts and
    figure, with the parameter tabs and folders as bands across it (docs/assets/hdue.css .hdue-params).
    """
    out, pending, grid = [], [], False
    for item in items:
        if item[0] == "heading":
            level = item[1]
            pending = [h for h in pending if h[0] < level] + [(level, item[2])]
            continue
        if pending and grid:
            out.append("</div>\n")
            grid = False
        for level, text in pending:
            # The wiki's == Tab == is level 2, its folders below it.
            band = "hdue-tab" if level <= 2 else "hdue-folder"
            out.append(f"{'#' * (level + 1)} {text} {{ .{band} }}\n")
        pending = []
        if not grid:
            out.append('<div class="hdue-params" markdown>\n')
            grid = True
        _, label, parm, text = item
        facts = details(definition, parm)
        attribute = (
            hou.text.decode(parm) if parm and parm.startswith("xn__") else parm
        )
        body = [paragraphs(text)] if text else []
        if facts:
            body.append(facts_html(facts))
        if attribute in FIGURES:
            body.append(
                f'<div class="hdue-figure" data-figure="{FIGURES[attribute]}"></div>'
            )
        out.append(
            '<div class="hdue-param" markdown>\n'
            f'<div class="hdue-param__name">{html.escape(label)}</div>\n'
            '<div class="hdue-param__body" markdown>\n\n'
            + "\n\n".join(body)
            + "\n\n</div>\n</div>\n"
        )
    if grid:
        out.append("</div>\n")
    return "\n".join(out)


def icon(definition, meta):
    """The node's icon copied next to the pages (config/Icons, or the asset's embedded SVG); None if it has none."""
    target = OUT / "icons"
    name = meta.get("icon", "").replace("/", "_")
    if name and (ICONS / f"{name}.svg").exists():
        shutil.copyfile(ICONS / f"{name}.svg", target / f"{name}.svg")
        return f"{name}.svg"
    if "IconSVG" in definition.sections():
        name = definition.nodeTypeName().replace("::", "_").replace(".", "_")
        (target / f"{name}.svg").write_text(
            definition.sections()["IconSVG"].contents(), encoding="utf-8"
        )
        return f"{name}.svg"
    return None


def page_name(definition, newest):
    """lop/hdueheightfog, with -<version> for an asset that a newer version of the same node replaces."""
    _, name, version = definition.nodeTypeName().split("::")
    return name if newest[name] == version else f"{name}-{version}"


def main():
    definitions = []
    for file in sorted(OTLS.glob("*.hda")):
        hou.hda.installFile(str(file))
        definitions += hou.hda.definitionsInFile(str(file))
    newest = {}
    for d in definitions:
        _, name, version = d.nodeTypeName().split("::")
        newest[name] = max(
            newest.get(name, version),
            version,
            key=lambda v: [int(x) for x in v.split(".")],
        )

    shutil.rmtree(OUT, ignore_errors=True)
    (OUT / "icons").mkdir(parents=True)
    rows = {context: [] for context in CONTEXTS}
    for d in definitions:
        if "Help" not in d.sections():
            raise SystemExit(
                f"{d.nodeTypeName()} has no help card: its builder must write one."
            )
        title, meta, summary, body, sections = parse(
            d.sections()["Help"].contents()
        )
        context = meta.get("context", d.nodeTypeCategory().name().lower())
        kind, _ = CONTEXTS[context]
        name = page_name(d, newest)
        if (
            name != d.nodeTypeName().split("::")[1]
        ):  # replaced by a newer version: say which one this is
            title += f" {d.nodeTypeName().split('::')[2]}"
        image = icon(d, meta)
        page = [HEADER]
        heading = (
            f'<img class="hdue-node-icon" src="../icons/{image}" alt=""> '
            if image
            else ""
        )
        page.append(f"# {heading}{title}\n")
        page.append(
            facts_html(
                [("Context", f"{kind} node"), ("Type", code(d.nodeTypeName()))]
            )
            + "\n"
        )
        if summary:
            page.append(f"{summary}\n{{ .hdue-node-summary }}\n")
        if paragraphs(body):
            page.append(paragraphs(body) + "\n")
        for key, label in (
            ("inputs", "Inputs"),
            ("outputs", "Outputs"),
            ("parameters", "Parameters"),
        ):
            if any(item[0] == "entry" for item in sections.get(key, [])):
                page.append(
                    f"## {label} {{ .hdue-section }}\n\n"
                    + section(d, sections[key])
                )
        path = OUT / context / f"{name}.md"
        path.parent.mkdir(exist_ok=True)
        path.write_text(
            "\n".join(page).rstrip() + "\n", encoding="utf-8", newline="\n"
        )
        rows[context].append((title, f"{context}/{name}.md", summary, image))

    index = [HEADER, "# Houdini nodes\n"]
    index.append(
        "The digital assets hdUE installs, with the help Houdini shows for them (F1 on a node), generated from the"
        " assets themselves.\n"
    )
    for context, (_, heading) in CONTEXTS.items():
        index.append(f"## {heading}\n\n| Node | Summary |\n|---|---|")
        for title, link, summary, image in sorted(rows[context]):
            picture = (
                f'<img class="hdue-node-icon" src="icons/{image}" alt=""> '
                if image
                else ""
            )
            index.append(f"| {picture}[{title}]({link}) | {summary} |")
        index.append("")
    (OUT / "index.md").write_text(
        "\n".join(index), encoding="utf-8", newline="\n"
    )

    nav = [
        NAV_START,
        '    { "Houdini nodes" = [\n',
        '      "reference/nodes/index.md",\n',
    ]
    for context, (kind, _) in CONTEXTS.items():
        nav.append(f'      {{ "{kind}s" = [\n')
        for title, link, _, _ in sorted(rows[context]):
            nav.append(f'        {{ "{title}" = "reference/nodes/{link}" }},\n')
        nav.append("      ] },\n")
    nav += ["    ] },\n", NAV_END]
    text = CONFIG.read_text(encoding="utf-8")
    start, end = text.index(NAV_START), text.index(NAV_END) + len(NAV_END)
    CONFIG.write_text(
        text[:start] + "".join(nav) + text[end:], encoding="utf-8", newline="\n"
    )
    print(f"{sum(len(r) for r in rows.values())} node pages in {OUT}")


if __name__ == "__main__":
    main()
