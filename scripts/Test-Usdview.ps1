# One usdview GUI check (usdview_hdue.py --hdue-check): fresh evidence, the check's own counts and, for some, a clean log.
param(
    [ValidateSet('smoke','camera','scene','materialx','textures','residency','opacity','glass','assets')][string]$Check='smoke',
    [string]$InputUsd='',
    [string]$Library='',
    [string]$GlassProfile='',
    [string]$RuntimeConfig='',
    [string]$OpenUsdRoot='',
    [string]$OutputDirectory=''
)
$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot 'Local-Paths.ps1')
$TaskRoot=Split-Path -Parent $PSScriptRoot
if ($Check -in 'opacity','glass' -and -not $InputUsd) {$InputUsd=Get-HdUELocalPath -Key review_scene}
if ($Check -eq 'materialx') {
    if (-not $InputUsd) {$InputUsd=Join-Path $TaskRoot 'samples\materialx\showcase.usda'}
    if (-not $Library) {$Library=Join-Path $TaskRoot 'out\materialx\library.json'}
}
if ($Check -eq 'textures' -and -not $InputUsd) {$InputUsd=Join-Path $TaskRoot 'samples\materialx\normal_udim_showcase\normal_udim.usda'}
if ($Check -in 'scene','residency','assets' -and -not $InputUsd) {throw "-Check $Check requires -InputUsd."}
if ($Check -in 'textures','residency' -and -not $Library) {throw "-Check $Check requires the -Library generated by Import-UsdMaterialX.ps1."}
if ($Check -eq 'glass' -and -not $GlassProfile) {throw '-Check glass requires -GlassProfile.'}
if ($Check -eq 'assets' -and -not $RuntimeConfig) {throw '-Check assets requires -RuntimeConfig.'}
$Run=New-HdUERun -Name "usdview-$Check" -Path $OutputDirectory
$Launch=@{OpenUsdRoot=$OpenUsdRoot; TestOutput=$Run; InputUsd=$InputUsd; MaterialXLibrary=$Library; GlassProfile=$GlassProfile; RuntimeConfig=$RuntimeConfig
          CameraPath=@{smoke='/Camera'; camera='/Camera'; materialx='/Camera'; textures='/Camera'; residency='/Camera'; assets='/Cameras/Level'}[$Check]}
$Arguments=@('--defaultsettings')
if ($Check -ne 'smoke') {$Arguments+=@('--hdue-check',$Check)}
& (Join-Path $PSScriptRoot 'Launch-Usdview.ps1') @Launch -UsdviewArguments $Arguments *> ($Run+'.log')
$R=Get-Content -Raw -LiteralPath (Join-Path $Run 'verified.json') | ConvertFrom-Json
$Complete=switch ($Check) {
    smoke {$R.frames.Count -eq 24 -and $R.picks.Count -eq 10 -and $R.same_process}
    camera {[bool]$R.camera_benchmark}
    scene {$R.passed -and $R.frames.Count -eq 18 -and $R.usd_unchanged -and $R.same_process}
    materialx {$R.passed -and $R.frames.Count -eq $(if ($R.inline_materialx_verified) {54} else {50}) -and $R.materialx_bindings.Count -eq 10 -and
               $R.effect_comparisons.Count -eq 20 -and $R.pathtracer_reset -and $R.source_unchanged -and $R.atomic_parameter_updates}
    textures {$R.passed -and $R.normal_and_udim_verified -and $R.frames.Count -eq 21 -and $R.normal_comparisons.Count -eq 8 -and
              $R.udim_checks.Count -eq 16 -and $R.udim_normal_checks.Count -eq 6}
    residency {$R.passed -and $R.residency_verified -and $R.frames.Count -eq 6 -and $R.failures.Count -eq 3}
    opacity {$R.passed -and $R.opacity_verified -and $R.targets.Count -eq 13 -and $R.comparisons.Count -eq 26 -and $R.frames.Count -eq 84 -and $R.usd_unchanged}
    glass {$R.passed -and $R.glass_verified -and $R.targets.Count -eq 5 -and $R.frames.Count -eq 64 -and $R.comparisons.Count -eq 10 -and
           $R.invalid_profile_rejected -and $R.usd_unchanged}
    assets {$R.passed -and $R.source_unchanged -and $R.frames.Count -ge 12 -and $R.instances.Count -ge 8}
}
if (-not $Complete -or $R.runtime_state -ne 4 -or ($Check -ne 'camera' -and $R.ue_initializations -ne 1)) {throw "Incomplete usdview $Check verification: $Run"}
$Log=[IO.File]::ReadAllText($Run+'.log').Replace([string][char]0,'')
if ($Check -in 'materialx','textures','opacity','glass' -and $Log -match '(?m)^hdUE:|Traceback|Fatal error|Coding Error:|Runtime Error:') {
    throw "usdview $Check verification reported errors: $Run.log"
}
if ($Check -eq 'camera') {$R.camera_benchmark | ConvertTo-Json}
if ($Check -eq 'glass') {Copy-Item -LiteralPath $GlassProfile -Destination (Join-Path $Run 'glass-profile.json')}
$Gallery=@{assets='create_asset_gallery.py'; opacity='create_opacity_gallery.py'; glass='create_glass_gallery.py'}[$Check]
if ($Gallery) {
    & uv run --python 3.11 (Join-Path $PSScriptRoot $Gallery) $Run
    if ($LASTEXITCODE) {throw "$Gallery failed."}
}
Write-Output "Verified usdview $($Check): $Run"
