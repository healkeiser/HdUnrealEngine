"""Write samples/docs/box.usda, the light study's box: a 1 m cube with slightly rounded edges and normals split at the
faces, so its edges catch a highlight as a real object's do. Run with hython:

    hython scripts/build_docs_box.py

Houdini builds it (Box, PolyBevel, Normal: the network an artist would use); this script only writes the result.
"""

from pathlib import Path

import hou

OUT = Path(__file__).resolve().parents[1] / "samples" / "docs" / "box.usda"


def build():
    sop = hou.node("/obj").createNode("geo").createNode("box")
    bevel = sop.createOutputNode("polybevel")
    bevel.parm("offset").set(
        0.015
    )  # 1.5 cm on the 1 m cube: subtle, wide enough for a highlight
    bevel.parm("divisions").set(4)
    normal = bevel.createOutputNode("normal")
    normal.parm("cuspangle").set(
        60
    )  # the bevel's segments smooth, the faces stay flat
    return normal.geometry()


def vectors(values):
    return ", ".join(f"({x:.6g}, {y:.6g}, {z:.6g})" for x, y, z in values)


def main():
    geo = build()
    points = [p.position() for p in geo.points()]
    counts, indices, normals = [], [], []
    for prim in geo.prims():
        # Houdini winds faces clockwise, USD (rightHanded) counter-clockwise: reverse each face.
        vertices = list(prim.vertices())[::-1]
        counts.append(len(vertices))
        indices += [v.point().number() for v in vertices]
        normals += [v.attribValue("N") for v in vertices]
    OUT.write_text(
        "#usda 1.0\n"
        "(\n"
        '    doc = """Generated by scripts/build_docs_box.py: a 1 m cube, edges bevelled 1.5 cm, normals split at'
        ' 60 degrees."""\n'
        '    defaultPrim = "box"\n'
        "    metersPerUnit = 1\n"
        '    upAxis = "Y"\n'
        ")\n\n"
        'def Mesh "box"\n'
        "{\n"
        f"    int[] faceVertexCounts = [{', '.join(map(str, counts))}]\n"
        f"    int[] faceVertexIndices = [{', '.join(map(str, indices))}]\n"
        f"    point3f[] points = [{vectors(points)}]\n"
        f'    normal3f[] normals = [{vectors(normals)}] (interpolation = "faceVarying")\n'
        '    uniform token subdivisionScheme = "none"\n'
        "}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT}: {len(points)} points, {len(counts)} faces")


if __name__ == "__main__":
    main()
