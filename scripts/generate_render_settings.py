def parse_post_process(header, defaults, enums, skipped):
    body = header[
        header.index("struct FPostProcessSettings\n") : header.index(
            "}; // struct FPostProcessSettings"
        )
    ]
    editor_only = [
        (m.start(), m.end())
        for m in re.finditer(r"#if WITH_EDITORONLY_DATA.*?#endif", body, re.S)
    ]
    settings = []
    for match in re.finditer(r"UPROPERTY\(", body):
        depth, i = 1, match.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(body[i], 0)
            i += 1
        specifiers = body[match.end() : i - 1]
        declaration = body[i : body.index(";", i)].strip()
        before = body[
            max(
                body.rfind(";", 0, match.start()),
                body.rfind("{", 0, match.start()),
            )
            + 1 : match.start()
        ]
        decl = re.match(
            r"(.+?)\s+(\w+)\s*(\[[^\]]*\])?\s*(:\s*1)?\s*(=.*)?$",
            declaration,
            re.S,
        )
        type_name, name = decl.group(1).strip(), decl.group(2)
        category = re.search(r'Category\s*=\s*"?([^",)]+)"?', specifiers)
        category = category.group(1).strip() if category else ""
        if (
            not category
            or category == "Overrides"
            or "UE_DEPRECATED" in before
            or name.endswith("_DEPRECATED")
            or any(a <= match.start() < b for a, b in editor_only)
        ):
            continue
        reason = (
            SKIP.get(name)
            or ("mobile renderer only" if category in SKIP_CATEGORIES else None)
            or ("fixed-size array" if decl.group(3) else None)
        )
        meta = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', specifiers))
        enum_name = re.sub(
            r"TEnumAsByte<(?:enum\s+)?(\w+)(?:::Type)?>", r"\1", type_name
        )
        if decl.group(4) or type_name == "bool":
            kind, size = "toggle", 1
        elif enum_name in enums:
            kind, size = "menu", 1
        elif "TObjectPtr" in type_name or type_name.endswith("*"):
            # Textures also take image files (imported at render time); curves only cooked assets.
            kind, size = ("image" if "UTexture" in type_name else "string"), 1
        elif type_name in TYPES:
            kind, size = TYPES[type_name]
        else:
            reason = reason or f"unsupported type {type_name}"
        if reason:
            skipped.append((name, reason))
            continue
        enum = enums.get(enum_name, [])
        default, note = HDUE_DEFAULTS.get(name, (None, None))
        value = (
            [default]
            if default is not None
            else default_value(
                defaults.get(name),
                {"color": "float", "image": "string"}.get(kind, kind),
                size,
                enum,
            )
        )
        help_text = (
            tooltip(
                re.findall(r"/\*\*.*?\*/|(?://[^\n]*\n\s*)+", before, re.S)[-1]
            )
            if re.search(r"/\*\*|//", before)
            else ""
        )
        if kind in ("string", "image"):
            help_text = help_text.strip()
            help_text += "" if help_text[-1:] in ("", ".", "!", "?") else "."
        if kind == "string":
            help_text += " Path of a cooked asset in the runtime project (/Game/... or /Engine/...)."
        elif kind == "image":
            help_text += (
                " An image file, imported at render time"
                + (
                    " (a lat-long panorama, made a cubemap as UE imports one)"
                    if "UTextureCube" in type_name
                    else ""
                )
                + ", or the path of a cooked texture in the runtime project (/Game/... or /Engine/...)."
            )
        if note:
            help_text = (
                help_text.strip()
                + ("" if help_text.strip()[-1:] in ("", ".", "!", "?") else ".")
                + " "
                + note
            ).strip()
        translucency = meta.get("TranslucencyType")
        settings.append(
            dict(
                attribute=f"unreal:postProcess:{name}",
                # UE has stray spaces in some (AutoExposureBias: "Exposure Compensation ").
                label=(meta.get("DisplayName") or "").strip()
                or label_from_name(name),
                category=category,
                kind=kind,
                size=size,
                default=value,
                help=help_text.strip(),
                menu=[(v, l) for v, l in enum],
                range=ranges(meta, kind),
                # UE's Details panel shows AdvancedDisplay properties under each group's "Advanced" expander.
                advanced="AdvancedDisplay" in specifiers,
                # The Details panel shows a translucency property only for its TranslucencyType
                # (PostProcessSettingsCustomization.cpp CustomizeProperty).
                hide=(
                    [
                        f'{houdini_name("unreal:postProcess:TranslucencyType")} != "ETranslucencyType::{translucency}"'
                    ]
                    if translucency
                    else []
                ),
            )
        )
    return settings


def ranges(meta, kind):
    """Houdini range (lo, hi, lo locked, hi locked): UE's ClampMin/ClampMax lock the value (UE clamps there), else
    UIMin/UIMax give the slider. Houdini has one range for both, so a clamp wins over the slider bound on its side.
    """

    def number(key):
        return float(meta[key]) if key in meta else None

    ui_lo, ui_hi = number("UIMin"), number("UIMax")
    clamp_lo, clamp_hi = number("ClampMin"), number("ClampMax")
    if (
        ui_hi is not None and ui_lo is not None and ui_hi < ui_lo
    ):  # UE's own metadata typo (LumenDiffuseColorBoost UIMax ".01")
        ui_hi = None
    lo = clamp_lo if clamp_lo is not None else ui_lo
    hi = clamp_hi if clamp_hi is not None else ui_hi
    if kind not in ("float", "int") or (lo is None and hi is None):
        return None
    # One open side: a slider of 10 from the bound that exists (or from the UI bound on the open side).
    lo = (
        lo
        if lo is not None
        else (ui_lo if ui_lo is not None else min(0.0, hi - 10))
    )
    hi = (
        hi
        if hi is not None
        else (ui_hi if ui_hi is not None and ui_hi > lo else max(lo, 0.0) + 10)
    )
    if hi < lo:
        return None
    return (lo, hi, lo == clamp_lo, hi == clamp_hi)


def parse_cvars(engine_source, names):
    """Declarations of the curated console variables: name -> (type, default, help, read-only)."""
    found = {}
    pattern = re.compile(
        r'(?:TAutoConsoleVariable<(\w+)>|FAutoConsoleVariableRef)\s*\w+\s*\(\s*TEXT\(\s*"([\w.]+)"\s*\)\s*,'
        r'\s*([^,]+?)\s*,\s*((?:TEXT\(\s*"(?:[^"\\]|\\.)*"\s*\)\s*)+)(.*?)\)\s*;',
        re.S,
    )
    for directory in ("Renderer", "Engine", "RenderCore"):
        for folder, _, files in os.walk(engine_source / "Runtime" / directory):
            for file in files:
                if not file.endswith(".cpp"):
                    continue
                text = (Path(folder) / file).read_text(
                    encoding="utf-8", errors="ignore"
                )
                if not any(name in text for name in names):
                    continue
                for (
                    type_name,
                    name,
                    default,
                    help_text,
                    flags,
                ) in pattern.findall(text):
                    if name not in names:
                        continue
                    if (
                        not type_name
                    ):  # FAutoConsoleVariableRef: the referenced variable's declaration
                        declared = re.search(
                            r"\b(int32|float|bool|int)\s+"
                            + re.escape(default)
                            + r"\s*=\s*([^;]+);",
                            text,
                        )
                        type_name, default = declared.groups()
                    lines = re.findall(
                        r'TEXT\(\s*"((?:[^"\\]|\\.)*)"\s*\)', help_text
                    )
                    found[name] = (
                        type_name,
                        default.replace("Scalability::DefaultQualityLevel", "3")
                        .strip()
                        .rstrip("f"),
                        "".join(lines).replace("\\n", " ").replace('\\"', "'"),
                        "ECVF_ReadOnly" in flags,
                    )
    return found


def ini_values(engine_root):
    """Console variables the runtime's config sets at startup: the Epic (3) scalability level, then the project."""
    values = {}
    for path, sections in (
        (engine_root / "Engine/Config/BaseScalability.ini", r"\w+Quality@3"),
        (
            ROOT / "unreal/HdUEBackend/Config/DefaultEngine.ini",
            r"/Script/Engine\.RendererSettings|SystemSettings",
        ),
    ):
        section = None
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("["):
                section = re.fullmatch(
                    r"\[(?:" + sections + r")\]", line.strip()
                )
            elif section and "=" in line and not line.startswith(";"):
                name, value = line.split("=", 1)
                values[name.strip()] = {"true": "1", "false": "0"}.get(
                    value.strip().lower(), value.strip()
                )
    return values


def project_settings_cvars(engine_root):
    """Console variables UE's Project Settings > Rendering shows (URendererSettings properties with a ConsoleVariable),
    except the AdvancedDisplay ones.
    """
    text = (
        engine_root
        / "Engine/Source/Runtime/Engine/Classes/Engine/RendererSettings.h"
    ).read_text(encoding="utf-8")
    shown = set()
    for match in re.finditer(r"UPROPERTY\((.*?)\)\)\s*\n", text, re.S):
        name = re.search(r'ConsoleVariable\s*=\s*"([^"]+)"', match.group(1))
        if name and "AdvancedDisplay" not in match.group(1):
            shown.add(name.group(1))
    return shown


def console_settings(engine_root):
    declared = parse_cvars(engine_root / "Engine/Source", {c[0] for c in CVARS})
    configured = ini_values(engine_root)
    project_settings = project_settings_cvars(engine_root)
    settings = []
    for name, label, folder, viewport, options in CVARS:
        type_name, default, help_text, read_only = declared.get(
            name,
            (
                options.get("type"),
                options.get("default"),
                options.get("help"),
                False,
            ),
        )
        if type_name is None:
            raise SystemExit(
                f"{name}: no declaration found in the engine source"
            )
        if read_only:
            raise SystemExit(
                f"{name} is read-only (ECVF_ReadOnly) and cannot change at runtime"
            )
        default = options.get("default", configured.get(name, default))
        if options.get("kind") == "toggle" or type_name == "bool":
            kind, value = "toggle", [str(default).lower() not in ("0", "false")]
        elif options.get("menu"):
            kind, value = "intmenu", [int(float(default))]
        elif type_name in ("int32", "int"):
            kind, value = "int", [int(float(default))]
        else:
            kind, value = "float", [float(default)]
        # (lo, hi, locked) or (lo, hi, lo locked, hi locked)
        bounds = options.get("range")
        if bounds and len(bounds) == 3:
            bounds = (*bounds, bounds[2])
        help_text = re.sub(
            r"\s+", " ", options.get("help") or help_text
        ).strip()
        settings.append(
            dict(
                attribute="unreal:cvar:" + name.replace(".", ":"),
                label=label,
                place=folder,
                category=folder.split("|")[-1],
                kind=kind,
                size=1,
                default=value,
                help=f"{help_text} Console variable {name} (process-wide).",
                menu=options.get("menu", []),
                range=bounds,
                advanced=not (
                    name.startswith("sg.")
                    or name in ESSENTIAL_CVARS
                    or name in project_settings
                ),
                viewport=viewport,
                cvar=name,
                declared_default=(
                    None if "default" in options else float(value[0])
                ),
            )
        )
    return settings


def ds_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ds_number(value):
    if isinstance(value, bool):
        return "1" if value else "0"
    return (
        repr(value)
        if isinstance(value, float) and not value.is_integer()
        else str(int(value))
    )


