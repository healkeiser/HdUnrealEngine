def hdue(name, label, place, kind, default, help_text, **options):
    """One of hdUE's own settings (unreal:<name>), placed at "Tab|Section" ("" above the tabs)."""
    return dict(
        attribute="unreal:" + name,
        label=label,
        place=place,
        category=options.pop("category"),
        kind=kind,
        size=1,
        default=[default],
        help=help_text,
        menu=options.pop("menu", []),
        range=options.pop("range", None),
        advanced=options.pop("advanced", False),
        **options,
    )


