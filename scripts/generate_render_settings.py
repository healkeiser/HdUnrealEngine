def houdini_name(text):
    """Houdini's parameter name for an attribute name (hou.text.encode): punycode with '_'."""
    basic = lambda c: c.isascii() and (c.isalnum() or c == "_")
    codes = [ord(c) for c in text]
    result = "".join(c for c in text if basic(c))
    if len(result) == len(text):
        return text
    base, tmin, tmax, skew, damp = 36, 1, 26, 38, 700

    def adapt(delta, count, first):
        delta = delta // damp if first else delta // 2
        delta += delta // count
        k = 0
        while delta > ((base - tmin) * tmax) // 2:
            delta //= base - tmin
            k += base
        return k + (base - tmin + 1) * delta // (delta + skew)

    digit = lambda d: chr(d + 22 + 75 * (d < 26))
    result += "_"
    handled = first = len(result) - 1
    n, delta, bias = 1, 0, 72
    while handled < len(codes):
        m = min(c for c in codes if c >= n and not basic(chr(c)))
        delta += (m - n) * (handled + 1)
        n = m
        for c in codes:
            if basic(chr(c)) or c < n:
                delta += 1
            elif c == n:
                q, k = delta, base
                while True:
                    t = (
                        tmin
                        if k <= bias
                        else tmax if k >= bias + tmax else k - bias
                    )
                    if q < t:
                        break
                    result += digit(t + (q - t) % (base - t))
                    q, k = (q - t) // (base - t), k + base
                result += digit(q)
                bias = adapt(delta, handled + 1, handled == first)
                delta, handled = 0, handled + 1
        delta, n = delta + 1, n + 1
    return "xn__" + result


def strip_comments(text):
    return re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.S)


def parse_enums(*sources):
    """Name -> [(import name, label)] for UENUMs; plain enums import by bare value names."""
    enums = {}
    pattern = re.compile(
        r"(?:namespace\s+(\w+)\s*\{\s*)?enum\s+(class\s+)?(\w+)\s*(?::\s*\w+)?\s*\{(.*?)\}",
        re.S,
    )
    for source in sources:
        for namespace, scoped, name, body in pattern.findall(source):
            owner = namespace or name
            entries = []
            for item in re.findall(
                r'(?:[^,("]|"[^"]*"|\((?:[^()"]|"[^"]*")*\))+',
                strip_comments(body),
            ):
                match = re.match(r"\s*(\w+)", item)
                if (
                    not match
                    or "UE_DEPRECATED" in item
                    or "Hidden" in item
                    or match.group(1).endswith("MAX")
                ):
                    continue
                value = match.group(1)
                label = re.search(r'DisplayName\s*=\s*"([^"]*)"', item)
                entries.append(
                    (
                        f"{owner}::{value}" if namespace or scoped else value,
                        label.group(1) if label else value,
                    )
                )
            enums[owner] = entries
    return enums


def parse_defaults(source):
    body = source[
        source.index("FPostProcessSettings::FPostProcessSettings()") :
    ]
    body = body[: body.index("\n}\n")]
    defaults = {}
    for name, expression in re.findall(r"^\s*(\w+)\s*=\s*(.+?);", body, re.M):
        defaults[name] = (
            expression  # the else branch: r.DefaultFeature.AutoExposure.ExtendDefaultLuminanceRange is 0
        )
    return defaults


def default_value(expression, kind, size, enum):
    if expression is None:
        return (
            [enum[0][0]]
            if kind == "menu"
            else {
                "float": [0.0] * size,
                "int": [0],
                "toggle": [False],
                "string": [""],
            }[kind]
        )
    expression = expression.replace(
        "FPostProcessSettings::kDefaultDepthOfFieldBladeCount", "5"
    )
    if kind == "menu":
        value = expression.split("::")[-1]
        return [next(v for v, _ in enum if v.split("::")[-1] == value)]
    if kind == "toggle":
        return [expression.strip() not in ("0", "false")]
    if kind == "string":
        return [""]
    if expression in ("FLinearColor::Black", "FVector2f::ZeroVector"):
        numbers = [0.0, 0.0, 0.0]
    else:
        numbers = [
            float(n.rstrip("f"))
            for n in re.findall(
                r"(?<![\w.])-?(?:\d+\.?\d*|\.\d+)f?", expression
            )
        ]
    if not numbers:
        raise SystemExit(f"cannot read the default {expression!r}")
    numbers = (
        (numbers + [numbers[-1]] * size)[:size]
        if kind == "float"
        else [int(numbers[0])]
    )
    return numbers


def label_from_name(name):
    name = re.sub(r"^b(?=[A-Z])", "", name)
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Za-z])(?=[0-9])", " ", name)


def tooltip(comment):
    text = re.sub(r"^\s*/\*\*?|\*/\s*$", "", comment.strip())
    text = " ".join(
        line.strip().lstrip("*").strip() for line in text.splitlines()
    )
    return re.sub(r"\s+", " ", text).strip()


