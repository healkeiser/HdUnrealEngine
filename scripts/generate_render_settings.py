def parse_post_process(header, defaults, enums, skipped):
    body = header[
        header.index("struct FPostProcessSettings\n") : header.index(
            "}; // struct FPostProcessSettings"
        )
    ]
    editor_only = [
        (m.start(), m.end())
        for m in re.finditer(r"#if WITH_EDITORONLY_DATA.*?#endif", body, re.S)
    ]
    settings = []
    for match in re.finditer(r"UPROPERTY\(", body):
        depth, i = 1, match.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(body[i], 0)
            i += 1
        specifiers = body[match.end() : i - 1]
        declaration = body[i : body.index(";", i)].strip()
        before = body[
            max(
                body.rfind(";", 0, match.start()),
                body.rfind("{", 0, match.start()),
            )
            + 1 : match.start()
        ]
        decl = re.match(
            r"(.+?)\s+(\w+)\s*(\[[^\]]*\])?\s*(:\s*1)?\s*(=.*)?$",
            declaration,
            re.S,
        )
        type_name, name = decl.group(1).strip(), decl.group(2)
        category = re.search(r'Category\s*=\s*"?([^",)]+)"?', specifiers)
        category = category.group(1).strip() if category else ""
        if (
            not category
            or category == "Overrides"
            or "UE_DEPRECATED" in before
            or name.endswith("_DEPRECATED")
            or any(a <= match.start() < b for a, b in editor_only)
        ):
            continue
        reason = (
            SKIP.get(name)
            or ("mobile renderer only" if category in SKIP_CATEGORIES else None)
            or ("fixed-size array" if decl.group(3) else None)
        )
        meta = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', specifiers))
        enum_name = re.sub(
            r"TEnumAsByte<(?:enum\s+)?(\w+)(?:::Type)?>", r"\1", type_name
        )
        if decl.group(4) or type_name == "bool":
            kind, size = "toggle", 1
        elif enum_name in enums:
            kind, size = "menu", 1
        elif "TObjectPtr" in type_name or type_name.endswith("*"):
            kind, size = "string", 1
        elif type_name in TYPES:
            kind, size = TYPES[type_name]
        else:
            reason = reason or f"unsupported type {type_name}"
        if reason:
            skipped.append((name, reason))
            continue
        enum = enums.get(enum_name, [])
        default, note = HDUE_DEFAULTS.get(name, (None, None))
        value = (
            [default]
            if default is not None
            else default_value(
                defaults.get(name),
                "float" if kind == "color" else kind,
                size,
                enum,
            )
        )
        help_text = (
            tooltip(
                re.findall(r"/\*\*.*?\*/|(?://[^\n]*\n\s*)+", before, re.S)[-1]
            )
            if re.search(r"/\*\*|//", before)
            else ""
        )
        if kind == "string":
            help_text += " Path of a cooked asset in the runtime project (/Game/... or /Engine/...)."
        if note:
            help_text = (
                help_text.strip()
                + ("" if help_text.strip()[-1:] in ("", ".", "!", "?") else ".")
                + " "
                + note
            ).strip()
        settings.append(
            dict(
                attribute=f"hdUE:postProcess:{name}",
                label=meta.get("DisplayName") or label_from_name(name),
                category=category,
                kind=kind,
                size=size,
                default=value,
                help=help_text.strip(),
                menu=[(v, l) for v, l in enum],
                range=ranges(meta, kind),
            )
        )
    return settings


def ranges(meta, kind):
    def number(key):
        return float(meta[key]) if key in meta else None

    lo, hi = number("UIMin"), number("UIMax")
    clamp_lo, clamp_hi = number("ClampMin"), number("ClampMax")
    lo = lo if lo is not None else clamp_lo
    hi = hi if hi is not None else clamp_hi
    if (
        hi is not None and lo is not None and hi < lo
    ):  # UE's own metadata typo (LumenDiffuseColorBoost UIMax ".01")
        hi = clamp_hi
    if lo is None or hi is None or hi < lo or kind not in ("float", "int"):
        return None
    return (lo, hi, lo == clamp_lo, hi == clamp_hi)


def parse_cvars(engine_source, names):
    """Declarations of the curated console variables: name -> (type, default, help, read-only)."""
    found = {}
    pattern = re.compile(
        r'(?:TAutoConsoleVariable<(\w+)>|FAutoConsoleVariableRef)\s*\w+\s*\(\s*TEXT\(\s*"([\w.]+)"\s*\)\s*,'
        r'\s*([^,]+?)\s*,\s*((?:TEXT\(\s*"(?:[^"\\]|\\.)*"\s*\)\s*)+)(.*?)\)\s*;',
        re.S,
    )
    for directory in ("Renderer", "Engine", "RenderCore"):
        for folder, _, files in os.walk(engine_source / "Runtime" / directory):
            for file in files:
                if not file.endswith(".cpp"):
                    continue
                text = (Path(folder) / file).read_text(
                    encoding="utf-8", errors="ignore"
                )
                if not any(name in text for name in names):
                    continue
                for (
                    type_name,
                    name,
                    default,
                    help_text,
                    flags,
                ) in pattern.findall(text):
                    if name not in names:
                        continue
                    if (
                        not type_name
                    ):  # FAutoConsoleVariableRef: the referenced variable's declaration
                        declared = re.search(
                            r"\b(int32|float|bool|int)\s+"
                            + re.escape(default)
                            + r"\s*=\s*([^;]+);",
                            text,
                        )
                        type_name, default = declared.groups()
                    lines = re.findall(
                        r'TEXT\(\s*"((?:[^"\\]|\\.)*)"\s*\)', help_text
                    )
                    found[name] = (
                        type_name,
                        default.replace("Scalability::DefaultQualityLevel", "3")
                        .strip()
                        .rstrip("f"),
                        "".join(lines).replace("\\n", " ").replace('\\"', "'"),
                        "ECVF_ReadOnly" in flags,
                    )
    return found


def ini_values(engine_root):
    """Console variables the runtime's config sets at startup: the Epic (3) scalability level, then the project."""
    values = {}
    for path, sections in (
        (engine_root / "Engine/Config/BaseScalability.ini", r"\w+Quality@3"),
        (
            ROOT / "unreal/HdUEBackend/Config/DefaultEngine.ini",
            r"/Script/Engine\.RendererSettings|SystemSettings",
        ),
    ):
        section = None
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("["):
                section = re.fullmatch(
                    r"\[(?:" + sections + r")\]", line.strip()
                )
            elif section and "=" in line and not line.startswith(";"):
                name, value = line.split("=", 1)
                values[name.strip()] = {"true": "1", "false": "0"}.get(
                    value.strip().lower(), value.strip()
                )
    return values


def console_settings(engine_root):
    declared = parse_cvars(engine_root / "Engine/Source", {c[0] for c in CVARS})
    configured = ini_values(engine_root)
    settings = []
    for name, label, folder, viewport, options in CVARS:
        type_name, default, help_text, read_only = declared.get(
            name,
            (
                options.get("type"),
                options.get("default"),
                options.get("help"),
                False,
            ),
        )
        if type_name is None:
            raise SystemExit(
                f"{name}: no declaration found in the engine source"
            )
        if read_only:
            raise SystemExit(
                f"{name} is read-only (ECVF_ReadOnly) and cannot change at runtime"
            )
        default = options.get("default", configured.get(name, default))
        if options.get("kind") == "toggle" or type_name == "bool":
            kind, value = "toggle", [str(default).lower() not in ("0", "false")]
        elif options.get("menu"):
            kind, value = "intmenu", [int(float(default))]
        elif type_name in ("int32", "int"):
            kind, value = "int", [int(float(default))]
        else:
            kind, value = "float", [float(default)]
        lo, hi, strict = options.get("range", (None, None, False))
        help_text = re.sub(
            r"\s+", " ", options.get("help") or help_text
        ).strip()
        settings.append(
            dict(
                attribute="hdUE:cvar:" + name.replace(".", ":"),
                label=label,
                category=folder,
                kind=kind,
                size=1,
                default=value,
                help=f"{help_text} Console variable {name} (process-wide).",
                menu=options.get("menu", []),
                range=(lo, hi, strict, strict) if lo is not None else None,
                viewport=viewport,
                cvar=name,
                declared_default=(
                    None if "default" in options else float(value[0])
                ),
            )
        )
    return settings


def ds_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ds_number(value):
    if isinstance(value, bool):
        return "1" if value else "0"
    return (
        repr(value)
        if isinstance(value, float) and not value.is_integer()
        else str(int(value))
    )


def ds_parm(setting, indent, viewport):
    name = houdini_name(setting["attribute"])
    control = houdini_name(setting["attribute"] + "_control")
    kind = setting["kind"]
    parm_type = {
        "float": "float",
        "color": "color",
        "int": "int",
        "intmenu": "int",
        "toggle": "toggle",
        "menu": "string",
        "string": "string",
    }[kind]
    usd_type = {
        "toggle": "bool",
        "menu": "string",
        "string": "string",
        "int": "int",
        "intmenu": "int",
        "color": "color3f",
    }.get(kind, "float" if setting["size"] == 1 else f"float{setting['size']}")
    defaults = " ".join(
        ds_string(v) if isinstance(v, str) else ds_number(v)
        for v in setting["default"]
    )
    lines = (
        []
        if viewport
        else [f'HDUE_CONTROL("{control}", {ds_string(setting["label"])})']
    )
    lines += [
        "parm {",
        f'    name    "{name}"',
        f"    label   {ds_string(setting['label'])}",
        f"    type    {parm_type}",
        f"    size    {setting['size']}",
        f"    default {{ {defaults} }}",
    ]
    if setting["range"]:
        lo, hi, strict_lo, strict_hi = setting["range"]
        lines.append(
            f"    range   {{ {ds_number(lo)}{'!' if strict_lo else ''} {ds_number(hi)}{'!' if strict_hi else ''} }}"
        )
    if setting["menu"]:
        items = " ".join(
            f"{ds_string(str(v))} {ds_string(l)}" for v, l in setting["menu"]
        )
        lines.append(f"    menu {{ {items} }}")
    if setting["help"]:
        lines.append(f"    help    {ds_string(setting['help'])}")
    lines.append(
        f"    parmtag {{ \"spare_category\" {ds_string(setting['category'])} }}"
    )
    if viewport:
        lines.append('    parmtag { "uiscope" "viewport" }')
    else:
        lines.append(f'    parmtag {{ "usdvaluetype" "{usd_type}" }}')
        condition = f"{{ {control} == block }} {{ {control} == none }}"
        if setting.get("tonemapper"):
            condition += f" {{ {TONEMAPPER} == 0 }}"
        lines.append(f'    disablewhen R"({condition})"')
    lines.append("}")
    return [indent + line for line in lines]


def group_id(*parts):
    return "_".join(re.sub(r"\W", "", p) for p in parts)


def ds_folder(kind, name, label, indent, *tags):
    return [
        f"{indent}{kind} {{",
        f'{indent}    name "{name}"',
        f"{indent}    label {ds_string(label)}",
    ] + [indent + "    " + tag for tag in tags]


def section_of(category):
    """(section, sub-section) of a UE category; Lens' sub-categories (Bloom, Depth of Field, ...) are sections."""
    parts = category.split("|")
    parts = parts[1:] if parts[0] == "Lens" else parts
    return parts[0], " - ".join(parts[1:])


def ds_sections(settings, indent, tab):
    """A collapsible section per category, holding a simple folder per sub-category (after the section's own settings)."""
    tree = {}
    for setting in settings:
        section, sub = section_of(setting["category"])
        tree.setdefault(section, {}).setdefault(sub, []).append(setting)
    lines = []
    for section, subs in tree.items():
        tags = [
            f'grouptag {{ "group_default" "{int(section in OPEN_SECTIONS)}" }}'
        ]
        if section in MODE_SECTIONS:
            tags.append(
                f'hidewhentab "{{ {RENDER_MODE} != {MODE_SECTIONS[section]} }}"'
            )
        lines += [""] + ds_folder(
            "groupcollapsible",
            group_id("hdUE", tab, section),
            section,
            indent,
            *tags,
        )
        for sub, entries in sorted(
            subs.items(), key=lambda item: item[0] != ""
        ):
            body = indent + "    "
            if sub:
                lines += [""] + ds_folder(
                    "groupsimple",
                    group_id("hdUE", tab, section, sub),
                    sub,
                    body,
                )
                body += "    "
            for setting in entries:
                lines += ds_parm(setting, body, False)
            if sub:
                lines.append(f"{indent}    }}")
        lines.append(f"{indent}}}")
    return lines


def ds_viewport(settings, indent):
    lines = ds_folder(
        "group",
        "hdUE_Quality",
        "Engine Quality",
        indent,
        'parmtag { "uiscope" "viewport" }',
    )
    for setting in settings:
        lines += ds_parm(setting, indent + "    ", True)
    return lines + [f"{indent}}}"]


def needs_tonemapper(category):
    top, _, sub = category.partition("|")
    return top in ("Color Grading", "Film", "Film Grain") or (
        top == "Lens" and not sub.startswith(("Camera", "Depth of Field"))
    )


def replace_generated(path, blocks):
    """Fill each generated block ("BEGIN ...: <key>") of the dialog script with blocks[key](indent)."""
    pattern = re.compile(
        r"^( *)"
        + re.escape(BEGIN)
        + r"([^\n]+)\n.*?^ *"
        + re.escape(END)
        + "$",
        re.S | re.M,
    )
    keys = []

    def fill(match):
        indent, key = match.groups()
        keys.append(key)
        return (
            indent
            + BEGIN
            + key
            + "\n"
            + "\n".join(blocks[key](indent))
            + "\n"
            + indent
            + END
        )

    text = pattern.sub(fill, path.read_text(encoding="utf-8"))
    if sorted(keys) != sorted(blocks):
        raise SystemExit(
            f"{path.name} has the generated blocks {keys}, expected {list(blocks)}"
        )
    path.write_text(text, encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--engine-root",
        type=Path,
        help="Default: engine_root (Local-Paths.ps1)",
    )
    parser.add_argument(
        "--defaults-json",
        type=Path,
        help="Write every generated setting at its default, for --renderer-settings",
    )
    args = parser.parse_args()
    if not args.engine_root:
        from local_paths import local_path

        args.engine_root = local_path("engine_root")
    source = args.engine_root / "Engine/Source"
    header = (source / "Runtime/Engine/Classes/Engine/Scene.h").read_text(
        encoding="utf-8"
    )
    enums = parse_enums(
        header,
        (source / "Runtime/Engine/Classes/Engine/EngineTypes.h").read_text(
            encoding="utf-8"
        ),
    )
    defaults = parse_defaults(
        (source / "Runtime/Engine/Private/Scene.cpp").read_text(
            encoding="utf-8"
        )
    )
    skipped = []
    post = parse_post_process(header, defaults, enums, skipped)
    for setting in post:
        setting["tonemapper"] = needs_tonemapper(setting["category"])
    console = console_settings(args.engine_root)

    if args.defaults_json:

        def value(s):
            v = s["default"]
            return (
                v[0]
                if len(v) == 1
                else " ".join(map(str, v)) if len(v) == 2 else v
            )

        settings = {s["attribute"]: value(s) for s in post + console}
        cvars = {
            s["cvar"]: s["declared_default"]
            for s in console
            if s["declared_default"] is not None
        }
        args.defaults_json.parent.mkdir(parents=True, exist_ok=True)
        args.defaults_json.write_text(
            json.dumps(
                dict(
                    version=1, settings=settings, declaredConsoleDefaults=cvars
                ),
                indent=1,
            )
        )
        return

    tabs = {"Engine Quality": console}
    for setting in post:
        tab = (
            "Post-Processing"
            if setting["tonemapper"]
            else POST_PROCESS_TABS.get(
                setting["category"].split("|")[0], "Lighting"
            )
        )
        tabs.setdefault(tab, []).append(setting)
    replace_generated(
        PARAMETERS / "HdUEHoudiniRendererPlugin_Global.ds",
        {
            tab: lambda indent, tab=tab, settings=settings: ds_sections(
                settings, indent, tab
            )
            for tab, settings in tabs.items()
        },
    )
    replace_generated(
        PARAMETERS / "HdUEHoudiniRendererPlugin_Viewport.ds",
        {
            "Engine Quality": lambda indent: ds_viewport(
                [s for s in console if s["viewport"]], indent
            )
        },
    )
    counts = {}
    for setting in post + console:
        counts[setting["category"]] = counts.get(setting["category"], 0) + 1
    for category, count in counts.items():
        print(f"{count:4} {category}")
    print(
        f"{len(post)} post-process settings, {len(console)} console variables"
    )
    for name, reason in skipped:
        print(f"skipped {name}: {reason}")


if __name__ == "__main__":
    assert houdini_name("hdUE:renderMode") == "xn__hdUErenderMode_tya"
    assert (
        houdini_name("hdUE:postProcess:BloomIntensity_control")
        == "xn__hdUEpostProcessBloomIntensity_control_90bl"
    )
    main()
