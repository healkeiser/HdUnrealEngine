"""Writes samples/conformance/points_curves/groom_attributes.usda: three curtains of UE hair strands (primvars:unreal:groom)
coloured three ways hdUE translates: a per-strand groom_color primvar (red), a bound UsdPreviewSurface (blue), and
displayColor on a groom drawn twice by a PointInstancer (green). Each check compares a curtain's normalized colour with
its hue; the instanced one also checks its second instance renders.

    python scripts/generate_groom_conformance.py
"""

import json
from pathlib import Path

OUT = (
    Path(__file__).resolve().parents[1]
    / "samples/conformance/points_curves/groom_attributes.usda"
)
COLUMNS, ROWS = 24, 3  # strands per curtain


def curtain(x0, y0, width=1.6, height=3.0):
    """Points, counts and widths of a curtain of slightly wavy vertical strands."""
    points, counts = [], []
    for c in range(COLUMNS):
        for r in range(ROWS):
            x = x0 + width * (c + 0.5) / COLUMNS
            z = -0.1 + 0.1 * r
            strand = [
                (x + 0.02 * ((k % 2) - 0.5), y0 + height * k / 7, z)
                for k in range(8)
            ]
            points += strand
            counts.append(len(strand))
    return points, counts


def curves_lines(name, x0, y0, extra, indent="    "):
    points, counts = curtain(x0, y0)
    pts = ", ".join(f"({x:.4g}, {y:.4g}, {z:.4g})" for x, y, z in points)
    lines = [
        f'{indent}def BasisCurves "{name}"' + extra[0],
        f"{indent}{{",
        f'{indent}    uniform token type = "linear"',
        f"{indent}    int[] curveVertexCounts = [{', '.join(map(str, counts))}]",
        f"{indent}    point3f[] points = [{pts}]",
        f'{indent}    float[] widths = [0.012] (interpolation = "constant")',
        f'{indent}    bool primvars:unreal:groom = 1 (interpolation = "constant")',
    ]
    lines += [indent + "    " + line for line in extra[1:]]
    lines.append(f"{indent}}}")
    return lines, len(counts)


def main():
    red, strands = curves_lines(
        "Attribute",
        -4.5,
        -1.5,
        [""],
    )
    red.insert(
        -1,
        f"        color3f[] primvars:groom_color = [{', '.join(['(0.8, 0.05, 0.03)'] * strands)}] "
        '(interpolation = "uniform")',
    )
    blue, _ = curves_lines(
        "Bound",
        -0.8,
        -1.5,
        [
            ' (prepend apiSchemas = ["MaterialBindingAPI"])',
            "rel material:binding = </Looks/Blue>",
        ],
    )
    green, _ = curves_lines(
        "Proto",
        -0.8,
        -1.5,
        [
            "",
            'color3f[] primvars:displayColor = [(0.05, 0.7, 0.08)] (interpolation = "constant")',
        ],
        indent="        ",
    )
    # Realtime against each hue. The Path Tracer's thin strands add white specular highlights and noise, paling the
    # same colours: its checks hold the colours it renders (each dominated by its hue) within 0.1.
    regions = {
        "red": [-4.3, -1.2, -3.1, 1.2],
        "blue": [-0.6, -1.2, 0.6, 1.2],
        "green": [2.4, -1.2, 3.6, 1.2],
    }
    names = {
        "red": "groom_color: the strands are red",
        "blue": "a bound Preview Surface: the strands are blue",
        "green": "displayColor on an instanced groom: green",
    }
    hues = {
        "realtime": {
            "red": [0.9, 0.08, 0.05],
            "blue": [0.1, 0.15, 0.95],
            "green": [0.1, 0.95, 0.1],
        },
        "pathtraced": {
            "red": [0.442, 0.296, 0.262],
            "blue": [0.168, 0.261, 0.571],
            "green": [0.279, 0.412, 0.309],
        },
    }
    checks = [
        {
            "name": f"{names[colour]} ({mode})",
            "modes": [mode],
            "color": {"region": regions[colour]},
            "rgb": hues[mode][colour],
            "tol": 0.25 if mode == "realtime" else 0.1,
        }
        for mode in hues
        for colour in regions
    ]
    checks.append(
        {
            "name": "the second instance renders",
            "value": {"region": [2.4, 2.0, 3.6, 4.0], "stat": "luma"},
            "min": 0.02,
        }
    )
    spec = {
        "schema": "hdUE groom",
        "feature": "groom_* attributes, bound materials and instancing",
        "frames": 1,
        "checks": checks,
    }
    text = "\n".join(
        [
            "#usda 1.0",
            "(",
            '    doc = """Generated by scripts/generate_groom_conformance.py: three curtains of UE hair strands, coloured'
            " by a groom_color primvar (red), a bound UsdPreviewSurface (blue), and displayColor on a groom a"
            ' PointInstancer draws twice (green, the second instance above the first)."""',
            "    customLayerData = {",
            '        string conformance = """'
            + json.dumps(spec, indent=1)
            + '"""',
            "    }",
            "    metersPerUnit = 1",
            '    upAxis = "Y"',
            "    startTimeCode = 1",
            "    endTimeCode = 1",
            "    timeCodesPerSecond = 24",
            '    renderSettingsPrimPath = "/Render/Settings"',
            "    subLayers = [@../common/stage.usda@]",
            ")",
            "",
            'def Scope "Looks"',
            "{",
            '    def Material "Blue"',
            "    {",
            "        token outputs:surface.connect = </Looks/Blue/S.outputs:surface>",
            '        def Shader "S"',
            "        {",
            '            uniform token info:id = "UsdPreviewSurface"',
            "            color3f inputs:diffuseColor = (0.04, 0.1, 0.8)",
            "            float inputs:roughness = 0.4",
            "            token outputs:surface",
            "        }",
            "    }",
            "}",
            "",
            *red,
            "",
            *blue,
            "",
            'def PointInstancer "Instanced"',
            "{",
            "    rel prototypes = </Instanced/Prototypes>",
            "    int[] protoIndices = [0, 0]",
            "    point3f[] positions = [(3.7, 0, 0), (3.7, 3.2, 0)]",
            '    def Scope "Prototypes"',
            "    {",
            *green,
            "    }",
            "}",
            "",
        ]
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
