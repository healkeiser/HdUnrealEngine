"""Write samples/docs/hair_strands.usdc, the hair page's groom: 12,000 strands of 16 points rooted on the top and back
of a 25 cm head (samples/docs/hair.usda places it), combed back along the scalp and falling under gravity, kept
outside the head. Widths taper from 0.6 mm at the root to 0.2 mm at the tip.

    uv run scripts/build_docs_hair.py
"""

import random
from pathlib import Path

from pxr import Gf, Usd, UsdGeom, Vt

OUT = (
    Path(__file__).resolve().parents[1]
    / "samples"
    / "docs"
    / "hair_strands.usdc"
)
STRANDS, POINTS = 12000, 16
RADIUS, LENGTH = 0.25, 0.45  # the head's radius and a strand's length, metres
ROOT_WIDTH, TIP_WIDTH = 0.0006, 0.0002


def strand(rng):
    # A root on the scalp: above the brow line, and not on the face (which looks at +Z).
    while True:
        n = Gf.Vec3d(
            rng.gauss(0, 1), rng.gauss(0, 1), rng.gauss(0, 1)
        ).GetNormalized()
        if n[1] > -0.15 and not (n[2] > 0.55 and n[1] < 0.55):
            break
    p = n * RADIUS
    # Combed back and down along the scalp: the comb direction without its part along the normal, lifted a little.
    comb = Gf.Vec3d(0, -0.6, -1)
    direction = (comb - n * Gf.Dot(comb, n) + n * 0.15).GetNormalized()
    step = LENGTH / (POINTS - 1)
    points = [p]
    for _ in range(POINTS - 1):
        direction = (
            direction + Gf.Vec3d(0, -0.22, 0)
        ).GetNormalized()  # gravity bends it down
        p = p + direction * step
        if (
            p.GetLength() < RADIUS * 1.01
        ):  # slides over the head instead of through it
            p = p.GetNormalized() * RADIUS * 1.01
        points.append(p)
    return points


def main():
    rng = random.Random(7)
    points, widths = [], []
    for _ in range(STRANDS):
        points += strand(rng)
        widths += [
            ROOT_WIDTH + (TIP_WIDTH - ROOT_WIDTH) * i / (POINTS - 1)
            for i in range(POINTS)
        ]
    stage = Usd.Stage.CreateNew(str(OUT))
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.y)
    curves = UsdGeom.BasisCurves.Define(stage, "/hair")
    stage.SetDefaultPrim(curves.GetPrim())
    curves.CreateTypeAttr(UsdGeom.Tokens.linear)
    curves.CreateCurveVertexCountsAttr(Vt.IntArray([POINTS] * STRANDS))
    curves.CreatePointsAttr(Vt.Vec3fArray([Gf.Vec3f(p) for p in points]))
    curves.CreateWidthsAttr(Vt.FloatArray(widths))
    curves.SetWidthsInterpolation(UsdGeom.Tokens.vertex)
    curves.GetPrim().SetMetadata(
        "documentation",
        "Generated by scripts/build_docs_hair.py: 12,000 strands on a 25 cm head.",
    )
    stage.GetRootLayer().Save()
    print(
        f"{OUT}: {STRANDS} strands, {len(points)} points, {OUT.stat().st_size // 1024} KB"
    )
    assert len(points) == STRANDS * POINTS


if __name__ == "__main__":
    main()
