"""Write plan 024's measuring scenes into out/repro/perf (generated, not tracked: the groom and the VDB take tens of
MB): one edit at frame 2 of each, timed in a 2-frame husk render with HDUE_TRACE_TIMING=1 and HDUE_TRACE_SCENE=1. Run
with hython (the volume's VDB is made with Houdini's SOPs):

    hython samples/repro/perf/build_edits.py

- edit_instancer.usda: a PointInstancer of 10,000 instances of a 5,000-triangle grid; frame 2 moves the instancer.
  edit_instancer_blur.usda is the same with an open shutter (motion blur).
- edit_volume.usda: one 256^3 density VDB (edit_volume.vdb); frame 2 moves it.
- edit_groom.usda: 50,000 hair curves of 8 points (primvars:unreal:groom); frame 2 moves them.
  edit_groom_instanced.usda: 4,000 curves under a PointInstancer of 4 instances; frame 2 moves the instancer.
- edit_fog.usda: one UnrealLocalFogVolume in front of a wall; frame 2 moves it.
- edit_materials.usda: 100 meshes sharing one UsdPreviewSurface whose diffuseColor changes at frame 2.

To measure: render frames 1-2 with husk on the runtime under test and compare the frame-2 "hdUE scene" lines of the
trace with the previous build's (scene prepare, UE apply, meshes moved, ...), then the frame-2 images.
"""

import math
import os
from pathlib import Path

from pxr import Gf, Sdf, Usd, UsdGeom, UsdRender, UsdShade, UsdVol, Vt

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "out" / "repro" / "perf"
COMMON = ROOT / "samples" / "conformance" / "common" / "stage.usda"


def stage_for(name, shutter=None):
    """A stage over the conformance scenes' camera, key light and render settings
    (samples/conformance/common/stage.usda), writing the beauty only.
    """
    stage = Usd.Stage.CreateNew(str(OUT / name))
    layer = stage.GetRootLayer()
    layer.documentation = "Generated by samples/repro/perf/build_edits.py: plan 024's measuring scenes."
    layer.subLayerPaths.append(Path(os.path.relpath(COMMON, OUT)).as_posix())
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.y)
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    stage.SetTimeCodesPerSecond(24)
    stage.SetStartTimeCode(1)
    stage.SetEndTimeCode(2)
    stage.SetMetadata("renderSettingsPrimPath", "/Render/Settings")
    world = UsdGeom.Xform.Define(stage, "/World")
    stage.SetDefaultPrim(world.GetPrim())
    if shutter:
        camera = UsdGeom.Camera(stage.OverridePrim("/Camera"))
        camera.CreateShutterOpenAttr(-shutter)
        camera.CreateShutterCloseAttr(shutter)
    settings = UsdRender.Settings(stage.OverridePrim("/Render/Settings"))
    settings.CreateResolutionAttr(Gf.Vec2i(256, 256))
    settings.CreateProductsRel().SetTargets(["/Render/Beauty"])
    return stage


def grid_mesh(stage, path, quads, size):
    """A quads x quads grid of 2 * quads^2 triangles, size wide, in the XY plane."""
    mesh = UsdGeom.Mesh.Define(stage, path)
    step = size / quads
    points = [
        Gf.Vec3f(-size / 2 + i * step, -size / 2 + j * step, 0)
        for j in range(quads + 1)
        for i in range(quads + 1)
    ]
    indices = []
    for j in range(quads):
        for i in range(quads):
            a = j * (quads + 1) + i
            indices += [a, a + 1, a + quads + 2, a + quads + 1]
    mesh.CreatePointsAttr(Vt.Vec3fArray(points))
    mesh.CreateFaceVertexCountsAttr(Vt.IntArray([4] * quads * quads))
    mesh.CreateFaceVertexIndicesAttr(Vt.IntArray(indices))
    mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    mesh.CreateExtentAttr([(-size / 2, -size / 2, 0), (size / 2, size / 2, 0)])
    return mesh


def moved(prim, start, end):
    """A translate op sampled at frames 1 and 2."""
    op = UsdGeom.Xformable(prim).AddTranslateOp()
    op.Set(Gf.Vec3d(*start), 1)
    op.Set(Gf.Vec3d(*end), 2)


def instancer(name, shutter=None):
    stage = stage_for(name, shutter)
    points = UsdGeom.PointInstancer.Define(stage, "/World/instancer")
    grid_mesh(
        stage, "/World/instancer/prototypes/tile", 50, 0.08
    )  # 5,000 triangles
    points.CreatePrototypesRel().SetTargets(
        ["/World/instancer/prototypes/tile"]
    )
    side = 100  # 10,000 instances
    points.CreatePositionsAttr(
        Vt.Vec3fArray(
            [
                Gf.Vec3f(-5 + (i + 0.5) * 0.1, -5 + (j + 0.5) * 0.1, 0)
                for j in range(side)
                for i in range(side)
            ]
        )
    )
    points.CreateProtoIndicesAttr(Vt.IntArray([0] * side * side))
    moved(points.GetPrim(), (0, 0, 0), (0.5, 0.25, 0))
    stage.Save()


def volume():
    import hou

    vdb = OUT / "edit_volume.vdb"
    geo = hou.node("/obj").createNode("geo")
    sphere = geo.createNode("sphere")
    sphere.parm("type").set("polymesh")
    fog = geo.createNode("vdbfrompolygons")
    fog.setInput(0, sphere)
    fog.parm("voxelsize").set(
        2 / 254
    )  # 256 voxels across the unit sphere, with its exterior band
    fog.parm("builddistance").set(False)
    fog.parm("buildfog").set(True)
    fog.parm("fillinterior").set(True)
    fog.geometry().saveToFile(str(vdb))
    geo.destroy()
    stage = stage_for("edit_volume.usda")
    field = UsdVol.OpenVDBAsset.Define(stage, "/World/volume/density")
    field.CreateFilePathAttr(Sdf.AssetPath("./edit_volume.vdb"))
    field.CreateFieldNameAttr("density")
    vol = UsdVol.Volume.Define(stage, "/World/volume")
    vol.CreateFieldRelationship("density", field.GetPath())
    UsdGeom.Xformable(vol).AddScaleOp().Set(Gf.Vec3f(3))
    moved(vol.GetPrim(), (0, 0, 0), (0.5, 0.25, 0))
    UsdGeom.Xformable(vol).SetXformOpOrder(
        list(reversed(UsdGeom.Xformable(vol).GetOrderedXformOps()))
    )
    stage.Save()


def curves(stage, path, count, points_each=8):
    """Count hair curves of points_each points, rooted on a 4 x 4 square, 0.5 tall."""
    curves = UsdGeom.BasisCurves.Define(stage, path)
    curves.CreateTypeAttr(UsdGeom.Tokens.linear)
    side = int(math.ceil(math.sqrt(count)))
    points = []
    for c in range(count):
        x, y = -2 + 4 * (c % side) / side, -2 + 4 * (c // side) / side
        for k in range(points_each):
            t = k / (points_each - 1)
            points.append(Gf.Vec3f(x + 0.05 * t * t, y + 0.5 * t, 0.02 * t))
    curves.CreatePointsAttr(Vt.Vec3fArray(points))
    curves.CreateCurveVertexCountsAttr(Vt.IntArray([points_each] * count))
    curves.CreateWidthsAttr(Vt.FloatArray([0.003]))
    curves.SetWidthsInterpolation(UsdGeom.Tokens.constant)
    UsdGeom.PrimvarsAPI(curves).CreatePrimvar(
        "unreal:groom", Sdf.ValueTypeNames.Bool, UsdGeom.Tokens.constant
    ).Set(True)
    return curves


def groom():
    stage = stage_for("edit_groom.usda")
    moved(
        curves(stage, "/World/hair", 50000).GetPrim(), (0, 0, 0), (0.5, 0.25, 0)
    )
    stage.Save()
    stage = stage_for("edit_groom_instanced.usda")
    points = UsdGeom.PointInstancer.Define(stage, "/World/instancer")
    curves(stage, "/World/instancer/prototypes/hair", 4000)
    points.CreatePrototypesRel().SetTargets(
        ["/World/instancer/prototypes/hair"]
    )
    points.CreatePositionsAttr(
        Vt.Vec3fArray(
            [Gf.Vec3f(x, y, 0) for x in (-2.5, 2.5) for y in (-2.5, 2.5)]
        )
    )
    points.CreateScalesAttr(Vt.Vec3fArray([Gf.Vec3f(0.5)] * 4))
    points.CreateProtoIndicesAttr(Vt.IntArray([0] * 4))
    moved(points.GetPrim(), (0, 0, 0), (0.5, 0.25, 0))
    stage.Save()


def fog():
    stage = stage_for("edit_fog.usda")
    settings = stage.GetPrimAtPath("/Render/Settings")
    # UE draws no local fog volume nearer than 10 m to the camera by default.
    settings.CreateAttribute(
        "unreal:cvar:r:LocalFogVolume:GlobalStartDistance",
        Sdf.ValueTypeNames.Float,
    ).Set(0)
    volume = stage.DefinePrim("/World/fog", "UnrealLocalFogVolume")
    volume.CreateAttribute(
        "unreal:localFogVolume:RadialFogExtinction", Sdf.ValueTypeNames.Float
    ).Set(2)
    volume.CreateAttribute(
        "unreal:localFogVolume:FogAlbedo", Sdf.ValueTypeNames.Color3f
    ).Set(Gf.Vec3f(0))
    moved(volume, (0, 0, 4), (0.5, 0.25, 4))
    UsdGeom.Xformable(volume).AddScaleOp().Set(Gf.Vec3d(3))
    wall = UsdGeom.Cube.Define(stage, "/World/wall")
    UsdGeom.Xformable(wall).AddScaleOp().Set(Gf.Vec3d(12, 12, 0.1))
    stage.Save()


def materials():
    stage = stage_for("edit_materials.usda")
    mat = UsdShade.Material.Define(stage, "/World/material")
    shader = UsdShade.Shader.Define(stage, "/World/material/surface")
    shader.CreateIdAttr("UsdPreviewSurface")
    color = shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f)
    color.Set(Gf.Vec3f(0.8, 0.2, 0.2), 1)
    color.Set(Gf.Vec3f(0.2, 0.6, 0.8), 2)
    mat.CreateSurfaceOutput().ConnectToSource(
        shader.ConnectableAPI(), "surface"
    )
    for j in range(10):
        for i in range(10):
            mesh = grid_mesh(stage, f"/World/tiles/t{j}{i}", 10, 0.9)
            UsdGeom.Xformable(mesh).AddTranslateOp().Set(
                Gf.Vec3d(i - 4.5, j - 4.5, 0)
            )
            UsdShade.MaterialBindingAPI.Apply(mesh.GetPrim()).Bind(mat)
    stage.Save()


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    instancer("edit_instancer.usda")
    instancer("edit_instancer_blur.usda", shutter=0.25)
    volume()
    groom()
    fog()
    materials()
