"""Write samples/repro/perf/many.usda, plan 023's measuring scene: 400 meshes of about 2,000 triangles each (a 20 x 20
grid of tiles that reference one 32 x 32 quad grid), 200 UsdPreviewSurface materials bound to two tiles each, one
RectLight and a camera. Run with hython:

    hython samples/repro/perf/build_scene.py

Also writes material_edit.usda: 200 fog-particle Points (each binds hdUE's native fog material, whose values reach UE
as material-parameter updates) whose frame 2 changes the albedo of 50, to time those updates in a 2-frame husk render.
"""

from pathlib import Path

from pxr import Gf, Sdf, Usd, UsdGeom, UsdLux, UsdRender, UsdShade, Vt

HERE = Path(__file__).resolve().parent
GRID = 20  # tiles per side
QUADS = 32  # quads per tile side: 2 * 32 * 32 = 2,048 triangles
MATERIALS = 200
EDITED = 50


def tile(stage):
    mesh = UsdGeom.Mesh.Define(stage, "/Prototypes/tile")
    step = 0.9 / QUADS
    points = [
        Gf.Vec3f(-0.45 + i * step, -0.45 + j * step, 0)
        for j in range(QUADS + 1)
        for i in range(QUADS + 1)
    ]
    indices = []
    for j in range(QUADS):
        for i in range(QUADS):
            a = j * (QUADS + 1) + i
            indices += [a, a + 1, a + QUADS + 2, a + QUADS + 1]
    mesh.CreatePointsAttr(Vt.Vec3fArray(points))
    mesh.CreateFaceVertexCountsAttr(Vt.IntArray([4] * QUADS * QUADS))
    mesh.CreateFaceVertexIndicesAttr(Vt.IntArray(indices))
    mesh.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    mesh.CreateExtentAttr([(-0.45, -0.45, 0), (0.45, 0.45, 0)])
    stage.GetPrimAtPath("/Prototypes").SetSpecifier(Sdf.SpecifierClass)


def material(stage, index):
    path = f"/Materials/m{index:03d}"
    mat = UsdShade.Material.Define(stage, path)
    shader = UsdShade.Shader.Define(stage, f"{path}/surface")
    shader.CreateIdAttr("UsdPreviewSurface")
    hue = index / MATERIALS
    shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(
        Gf.Vec3f(0.2 + 0.6 * hue, 0.5, 0.8 - 0.6 * hue)
    )
    shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.5)
    mat.CreateSurfaceOutput().ConnectToSource(
        shader.ConnectableAPI(), "surface"
    )
    return mat


def build(path):
    stage = Usd.Stage.CreateNew(str(path))
    stage.GetRootLayer().documentation = "Generated by samples/repro/perf/build_scene.py: plan 023's measuring scene."
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    stage.SetStartTimeCode(1)
    stage.SetEndTimeCode(3)
    world = UsdGeom.Xform.Define(stage, "/World")
    stage.SetDefaultPrim(world.GetPrim())
    tile(stage)
    materials = [material(stage, i) for i in range(MATERIALS)]
    for j in range(GRID):
        for i in range(GRID):
            prim = stage.DefinePrim(f"/World/tiles/t{j:02d}_{i:02d}", "Mesh")
            prim.GetReferences().AddInternalReference("/Prototypes/tile")
            UsdGeom.Xformable(prim).AddTranslateOp().Set(
                Gf.Vec3d(i - GRID / 2 + 0.5, j - GRID / 2 + 0.5, 0)
            )
            UsdShade.MaterialBindingAPI.Apply(prim).Bind(
                materials[(j * GRID + i) % MATERIALS]
            )
    light = UsdLux.RectLight.Define(stage, "/World/light")
    light.CreateIntensityAttr(1)
    light.CreateExposureAttr(3)
    light.CreateWidthAttr(10)
    light.CreateHeightAttr(10)
    UsdGeom.Xformable(light).AddTranslateOp().Set(Gf.Vec3d(0, 0, 12))
    camera = UsdGeom.Camera.Define(stage, "/World/camera")
    # USD lens values are tenths of a scene unit: in this metre stage, 20 mm is 0.2.
    camera.CreateFocalLengthAttr(0.2)
    camera.CreateHorizontalApertureAttr(0.36)
    camera.CreateVerticalApertureAttr(0.36)
    UsdGeom.Xformable(camera).AddTranslateOp().Set(Gf.Vec3d(0, -18, 18))
    UsdGeom.Xformable(camera).AddRotateXOp().Set(45)
    settings = UsdRender.Settings.Define(stage, "/Render/Settings")
    settings.CreateResolutionAttr(Gf.Vec2i(512, 512))
    settings.CreateCameraRel().SetTargets([camera.GetPath()])
    settings.GetPrim().CreateAttribute(
        "unreal:renderMode", Sdf.ValueTypeNames.Token
    ).Set("realtime")
    stage.SetMetadata("renderSettingsPrimPath", "/Render/Settings")
    stage.Save()


def fog_scene(path, base):
    """Fog particles over many.usda's tiles: one Points prim of one point per fog material."""
    layer = Sdf.Layer.CreateNew(str(path))
    layer.subLayerPaths.append(f"./{base.name}")
    stage = Usd.Stage.Open(layer)
    for index in range(MATERIALS):
        points = UsdGeom.Points.Define(stage, f"/World/fog/p{index:03d}")
        points.CreatePointsAttr(
            [(index % GRID - GRID / 2, index // GRID - 5, 1)]
        )
        widths = points.CreateWidthsAttr([0.5])
        primvars = UsdGeom.PrimvarsAPI(points)
        primvars.CreatePrimvar(
            "unreal:fog:extinction", Sdf.ValueTypeNames.Float, "constant"
        ).Set(0.5)
        albedo = primvars.CreatePrimvar(
            "unreal:fog:albedo", Sdf.ValueTypeNames.Color3f, "constant"
        )
        if index < EDITED:
            # Hydra re-syncs a Points prim for its widths, not for an unreal:fog primvar alone.
            widths.Set([0.5], 1)
            widths.Set([0.51], 2)
            albedo.Set(Gf.Vec3f(1, 1, 1), 1)
            albedo.Set(Gf.Vec3f(0.9, 0.2, 0.1), 2)
        else:
            albedo.Set(Gf.Vec3f(1, 1, 1))
    for key in ("defaultPrim", "renderSettingsPrimPath"):
        layer.pseudoRoot.SetInfo(
            key, Usd.Stage.Open(str(base)).GetMetadata(key)
        )
    layer.pseudoRoot.SetInfo("metersPerUnit", 1.0)
    layer.pseudoRoot.SetInfo("upAxis", "Z")
    layer.startTimeCode, layer.endTimeCode = 1, 3
    layer.Save()


if __name__ == "__main__":
    for name in ("many.usda", "material_edit.usda"):
        (HERE / name).unlink(missing_ok=True)
    build(HERE / "many.usda")
    fog_scene(HERE / "material_edit.usda", HERE / "many.usda")
